-- V2: RBAC + simulated Active Directory groups (PostgreSQL prod)

CREATE TABLE PERMISSIONS (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE        VARCHAR(50)  NOT NULL,
    DESCRIPTION VARCHAR(255) NOT NULL,
    MODULE      VARCHAR(50)  NOT NULL DEFAULT 'CORE',
    CONSTRAINT UK_PERMISSIONS_CODE UNIQUE (CODE)
);

CREATE TABLE APP_ROLES (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME        VARCHAR(50)  NOT NULL,
    DESCRIPTION VARCHAR(255),
    CONSTRAINT UK_APP_ROLES_NAME UNIQUE (NAME)
);

CREATE TABLE ROLE_PERMISSIONS (
    ROLE_ID       BIGINT NOT NULL,
    PERMISSION_ID BIGINT NOT NULL,
    PRIMARY KEY (ROLE_ID, PERMISSION_ID),
    CONSTRAINT FK_RP_ROLE FOREIGN KEY (ROLE_ID) REFERENCES APP_ROLES (ID),
    CONSTRAINT FK_RP_PERM FOREIGN KEY (PERMISSION_ID) REFERENCES PERMISSIONS (ID)
);

CREATE TABLE DIRECTORY_GROUPS (
    ID                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME                VARCHAR(100) NOT NULL,
    DESCRIPTION         VARCHAR(255),
    DISTINGUISHED_NAME  VARCHAR(255) NOT NULL,
    CONSTRAINT UK_DIRECTORY_GROUPS_NAME UNIQUE (NAME),
    CONSTRAINT UK_DIRECTORY_GROUPS_DN UNIQUE (DISTINGUISHED_NAME)
);

CREATE TABLE GROUP_ROLES (
    GROUP_ID BIGINT NOT NULL,
    ROLE_ID  BIGINT NOT NULL,
    PRIMARY KEY (GROUP_ID, ROLE_ID),
    CONSTRAINT FK_GR_GROUP FOREIGN KEY (GROUP_ID) REFERENCES DIRECTORY_GROUPS (ID),
    CONSTRAINT FK_GR_ROLE FOREIGN KEY (ROLE_ID) REFERENCES APP_ROLES (ID)
);

CREATE TABLE USER_GROUPS (
    USER_ID  BIGINT NOT NULL,
    GROUP_ID BIGINT NOT NULL,
    PRIMARY KEY (USER_ID, GROUP_ID),
    CONSTRAINT FK_UG_USER FOREIGN KEY (USER_ID) REFERENCES USERS (ID),
    CONSTRAINT FK_UG_GROUP FOREIGN KEY (GROUP_ID) REFERENCES DIRECTORY_GROUPS (ID)
);
